import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=readFileSync('supabase/functions/email/logic.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {reminderMail,testMail,resetPasswordHtml,bilingualResetPasswordHtml}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
mkdirSync('outputs/email-templates',{recursive:true});
mkdirSync('supabase/templates',{recursive:true});
const reminder=reminderMail({id:'preview',name:'Asigurare RCA · Dacia Duster',expires:'2026-12-01'},7);
const hostile=reminderMail({id:'preview',name:'<img src=x onerror="alert(1)"> & RCA',expires:'2026-12-01'},0);
assert(!hostile.html.includes('<img'));
assert(hostile.html.includes('&lt;img'));
assert(hostile.html.includes('&amp; RCA'));
assert(reminder.text.includes('01.12.2026'));
assert(reminder.html.includes('href="https://duevo.pages.dev/reminders"'));
assert(reminderMail({id:'preview',name:'Dentist',expires:'2026-12-01',event_time:'14:30:00'},-15).html.includes('14:30'));
const reset=resetPasswordHtml();
assert(reset.includes('href="{{ .ConfirmationURL }}"'));
assert(!reset.includes('activat alertele'));
writeFileSync('supabase/templates/reset-password.html',bilingualResetPasswordHtml());
writeFileSync('outputs/email-templates/test-en.html',testMail('en').html);
writeFileSync('outputs/email-templates/reminder-en.html',reminderMail({id:'preview',name:'Poliță pentru Ștefan',expires:'2026-12-01'},7,'en').html);
writeFileSync('outputs/email-templates/reset-password-en.html',resetPasswordHtml('https://duevo.pages.dev/reset-password','en'));
assert(testMail('en').html.includes('lang="en"'));
assert(bilingualResetPasswordHtml().includes('{{ if eq .Data.duevo_language "en" }}'));
writeFileSync('outputs/email-templates/test.html',testMail().html);
writeFileSync('outputs/email-templates/reminder.html',reminder.html);
writeFileSync('outputs/email-templates/reset-password.html',resetPasswordHtml('https://duevo.pages.dev/reset-password'));
console.log('PASS: escaped user content, Romanian date/time, reminder links, recovery placeholder. Generated email previews and Supabase reset template.');
